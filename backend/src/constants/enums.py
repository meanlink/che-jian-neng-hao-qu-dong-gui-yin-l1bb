from enum import Enum
class Role(str, Enum):
    admin = 'admin'
    analyst = 'analyst'
    viewer = 'viewer'
class JobStatus(str, Enum):
    queued = 'queued'
    running = 'running'
    completed = 'completed'
    failed = 'failed'
class LedgerBatchStatus(str, Enum):
    pending = 'pending'
    posted = 'posted'
    rejected = 'rejected'
class LedgerEntryStatus(str, Enum):
    pending = 'pending'
    posted = 'posted'
class LedgerEntryType(str, Enum):
    original = 'original'
    reversal = 'reversal'
